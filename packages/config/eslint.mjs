import js from '@eslint/js';
import tseslint from 'typescript-eslint';

// Physical-direction Tailwind classes break RTL; use ms-/me-/ps-/pe-/start-/end- instead.
// Matches ml-4, -mr-2, md:pl-3, left-0, rounded-l-md, border-r, text-left, float-right, ...
const PHYSICAL_CLASS =
  '(^|\\s|:)-?(m[lr]|p[lr]|left|right|scroll-m[lr]|scroll-p[lr]|rounded-[lr]|rounded-[tb][lr]|border-[lr])-' +
  '|(^|\\s|:)(rounded|border)-[lr](\\s|$)' +
  '|(^|\\s|:)(text|float|clear)-(left|right)(\\s|$)';

const physicalMessage =
  'Use logical Tailwind classes (ms-, me-, ps-, pe-, start-, end-) so RTL works.';

export default tseslint.config(
  {
    ignores: [
      '**/dist/**',
      '**/node_modules/**',
      '**/.turbo/**',
      '.claude/**',
      'coverage/**',
      // Generated by `pnpm contracts:gen`.
      'apps/web/src/api/generated.ts',
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    files: ['**/*.cjs'],
    languageOptions: {
      sourceType: 'commonjs',
      globals: { module: 'writable', require: 'readonly' },
    },
  },
  {
    files: ['apps/web/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-syntax': [
        'error',
        { selector: `Literal[value=/${PHYSICAL_CLASS}/]`, message: physicalMessage },
        { selector: `TemplateElement[value.raw=/${PHYSICAL_CLASS}/]`, message: physicalMessage },
        {
          selector: 'JSXText[value=/\\S/]',
          message: 'No hard-coded UI text: add ar and en keys in packages/i18n and render t().',
        },
      ],
    },
  },
);
